// Arithmetic Operators

let a = 10;
let b = 3;

console.log(a + b);
console.log(a - b);
console.log(a * b);
console.log(a / b);
console.log(a % b);
console.log(a ** b);


// Assignment Operators

let x = 10;

x += 5;
console.log(x);

x -= 3;
console.log(x);

x *= 2;
console.log(x);

x /= 4;
console.log(x);


// Comparison Operators

let age = 20;

console.log(age > 18);
console.log(age < 18);
console.log(age >= 18);
console.log(age <= 18);
console.log(age === 20);
console.log(age !== 18);


// Logical Operators

let hasID = true;
let hasTicket = true;

console.log(hasID && hasTicket);
console.log(hasID || hasTicket);
console.log(!hasID);


// Increment and Decrement

let count = 5;

count++;
console.log(count);

count--;
console.log(count);


// Ternary Operator

let number = 10;

let result = number % 2 === 0 ? "Even" : "Odd";

console.log(result);